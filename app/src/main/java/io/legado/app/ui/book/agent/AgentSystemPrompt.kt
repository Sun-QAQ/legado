internal fun composeAgentSystemPrompt(
    personaPrompt: String,
    presetPrompt: String,
    toolOverview: String
): String = listOfNotNull(
    presetPrompt.takeIf { it.isNotBlank() },
    personaPrompt,
    AGENT_PERSONA_CONTINUITY,
    AGENT_TOOL_RULES,
    "当前可用工具（名称、参数和能力以工具定义为准）：\n$toolOverview"
).joinToString("\n\n")
